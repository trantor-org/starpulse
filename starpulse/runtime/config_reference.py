"""Regenerate the settings reference in `docs/serving.md`: `python -m starpulse.runtime.config_reference`.

The reference is rendered from the JSON Schema of `config_model.ConfigFile` and replaces what sits between the
`config-reference` markers; the doc's narrative around it is hand-written. CI regenerates it and fails on a diff.
"""

import re
from pathlib import Path

from starpulse.runtime.config_model import ConfigFile

DOC = Path(__file__).resolve().parents[2] / "docs" / "serving.md"
BEGIN_MARK = "<!-- config-reference:begin"
BEGIN = "<!-- config-reference:begin (generated by `python -m starpulse.runtime.config_reference`; edit the Field descriptions in starpulse/runtime/config_model.py) -->"
END = "<!-- config-reference:end -->"

_SCALARS = {"string": "text", "integer": "whole number", "number": "number", "boolean": "true or false"}


def _type(node: dict, defs: dict) -> str:
    """How an operator reads the type of a schema `node`, such as `list of text` or `whole number, 1 or more`."""
    if "$ref" in node:
        return f"`{defs[node['$ref'].rsplit('/', 1)[-1]]['title']}` table"
    if "anyOf" in node:
        return " or ".join(_type(option, defs) for option in node["anyOf"] if option != {"type": "null"})
    if "const" in node:
        return f'`"{node["const"]}"`'
    if "enum" in node:
        return " or ".join(f'`"{value}"`' for value in node["enum"])
    kind = node.get("type")
    if kind == "array":
        return f"list of {_type(node['items'], defs)}"
    if kind == "object":
        values = node.get("additionalProperties")
        return f"table of {_type(values, defs)}" if isinstance(values, dict) and values else "table"
    text = _SCALARS.get(kind, "any value")
    if "minimum" in node:
        text += f", {node['minimum']} or more"
    if "exclusiveMinimum" in node:
        text += f", above {node['exclusiveMinimum']}"
    return text


def _literal(value: object) -> str:
    """A default as TOML spells it."""
    if isinstance(value, bool):
        return str(value).lower()
    return f'"{value}"' if isinstance(value, str) else str(value)


def _entry(key: str, node: dict, required: bool, defs: dict) -> str:
    """One setting: its key, type, default and description."""
    facts = [_type(node, defs)]
    if node.get("deprecated"):
        facts.append("retired")
    if required:
        facts.append("required")
    elif node.get("default") not in (None, [], {}):
        facts.append(f"default `{_literal(node['default'])}`")
    return f"- `{key}` ({', '.join(facts)}): {node.get('description', '')}"


def _section(schema: dict, defs: dict) -> str:
    required = set(schema.get("required", []))
    entries = [_entry(key, node, key in required, defs) for key, node in schema["properties"].items()]
    return f"#### {schema['title']}\n\n" + "\n".join(entries)


def reference() -> str:
    """The settings reference: the top-level keys, then each table `starpulse.toml` takes."""
    schema = ConfigFile.model_json_schema()
    defs = schema.pop("$defs")
    tables = sorted(defs.values(), key=lambda table: table["title"].lstrip("["))
    sections = [_section(schema, defs), *(_section(table, defs) for table in tables)]
    return "\n\n".join(sections)


def render(text: str) -> str:
    """`text` with the generated block between the markers replaced by the current reference."""
    block = re.compile(f"{re.escape(BEGIN_MARK)}.*?{re.escape(END)}", re.DOTALL)
    if not block.search(text):
        raise SystemExit(f"{DOC} has no {BEGIN_MARK} ... {END} block to regenerate")
    return block.sub(lambda _: f"{BEGIN}\n\n{reference()}\n\n{END}", text)


if __name__ == "__main__":
    DOC.write_text(render(DOC.read_text()))
